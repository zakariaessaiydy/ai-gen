// =============================================================================
// STATE AS A FUNCTION OF THE GLOBAL FRAME.
// Every one of these returns its frame-0 value at f = END-1 by construction — each is a
// product of ramps that is 1 (or 0) at both ends. The loop is authored, not debugged in.
// =============================================================================

/** in -> hold -> out. */
const band = (f: number, a: number, b: number, c: number, d: number) =>
  EASE_OUT(prog(f, a, b)) * (1 - EASE_INOUT(prog(f, c, d)));

/** A short pop on a readout the narration has just named. */
const pop = (f: number, at: number) => band(f, at, at + 7, at + 26, at + 44);

/** How much one-on-one time this pair has had. 1 at f=0 (the finished week), rewound to 0 by
 *  the setup, and rebuilt to 1 by its own turn — so f=END-1 is f=0 again, edge for edge. */
const chargeAt = (key: string, f: number): number => {
  const rewound = 1 - EASE_INOUT(prog(f, DRAIN_A, DRAIN_B));
  const t = TURN_OF.get(key);
  const turn = t ? EASE_OUT(prog(f, t.a, t.b)) : 0;
  return Math.max(rewound, turn);
};

/** GRAN's presence, and the presence of each line she brings with her. */
const granAt = (f: number) =>
  EASE_OUT(prog(f, GRAN_A, GRAN_B)) * (1 - EASE_INOUT(prog(f, GRAN_OUT_A, GRAN_OUT_B)));

const newEdgeAt = (j: number, f: number) =>
  EASE_OUT(prog(f, NEW_IN[j], NEW_IN[j] + NEW_DUR)) * (1 - EASE_INOUT(prog(f, GRAN_OUT_A, GRAN_OUT_B)));

const presenceAt = (key: string, f: number): number => {
  if (KEY4.has(key)) return 1;
  const j = NEW_PAIRS.findIndex((p) => p.key === key);
  return j < 0 ? 0 : newEdgeAt(j, f);
};

const hullAt = (f: number) => band(f, HULL_A, HULL_B, HULL_C, HULL_D);
const dimAt = (f: number) =>
  1 - 0.28 * EASE_INOUT(prog(f, DIM_A, DIM_B)) * (1 - EASE_INOUT(prog(f, UNDIM_A, UNDIM_B)));

/** 1 at f=0 and at f=END-1; 0 only while the card is asking. */
const answerOpAt = (f: number) =>
  Math.min(1, 1 - EASE_INOUT(prog(f, ANS_OUT_A, ANS_OUT_B)) + EASE_OUT(prog(f, ANS_IN_A, ANS_IN_B)));

const chipOpAt = (f: number) =>
  Math.min(1, 1 - EASE_INOUT(prog(f, CHIP_OUT_A, CHIP_OUT_B)) + EASE_OUT(prog(f, CHIP_IN_A, CHIP_IN_B)));

const ringOf = (key: string, f: number): number => {
  if (key === K_COUPLE) return band(f, RING1_A, RING1_B, TURNS[4].a - 4, TURNS[4].a + 16);
  if (key === K_SIBS) return band(f, RING2_A, RING2_B, TURNS[5].a - 4, TURNS[5].a + 16);
  return 0;
};

/** The six edges flare in turn, twice, so the readout is seen to be counting them. */
const flareAt = (i: number, f: number) =>
  Math.max(
    band(f, SWEEP1_A + i * SWEEP1_STEP, SWEEP1_A + i * SWEEP1_STEP + 7, SWEEP1_A + i * SWEEP1_STEP + 14, SWEEP1_A + i * SWEEP1_STEP + 24),
    band(f, SWEEP2_A + i * SWEEP2_STEP, SWEEP2_A + i * SWEEP2_STEP + 6, SWEEP2_A + i * SWEEP2_STEP + 12, SWEEP2_A + i * SWEEP2_STEP + 20),
  );

const titleOpAt = (f: number) =>
  Math.min(1, 1 - EASE_INOUT(prog(f, TITLE_OUT_A, TITLE_OUT_B)) + EASE_OUT(prog(f, TITLE_IN_A, TITLE_IN_B)));

/** The whole board breathes 10px between the hook and the wrap, and lands back where it began. */
const driftAt = (f: number) =>
  f < 600 ? mix(-10, 0, EASE_OUT(prog(f, 0, 110))) : mix(0, -10, EASE_INOUT(prog(f, TITLE_IN_A, END - 1)));

// =============================================================================
// THE BOARD — the one persistent thing the whole video happens on. The beats only switch
// pieces of it on; nothing ever cuts.
// =============================================================================
const Board: React.FC<{ from: number }> = ({ from }) => {
  const f = useCurrentFrame() + from; // GLOBAL frame

  // ---- the household on THIS frame -------------------------------------------------------
  const gran = granAt(f);
  const charge = (k: string) => chargeAt(k, f);
  const weight = (k: string) => presenceAt(k, f);

  // The ring opens up to make room for a fifth person as she arrives, so nobody teleports.
  const anchors: Pt[] = ANCH5.map((a5, i) => (i < N4 ? { x: mix(ANCH4[i].x, a5.x, gran), y: mix(ANCH4[i].y, a5.y, gran) } : a5));
  const P = relax(anchors, PAIRS5, charge, { near: 330, far: 470, weightOf: weight });

  // ---- every number below is a COUNT of what is drawn above, never a constant -------------
  const nodesDrawn = N4 + (gran >= 0.5 ? 1 : 0);
  const edgesDrawn = PAIRS5.filter((p) => presenceAt(p.key, f) >= 0.5).length;
  const fedPairs = PAIRS5.filter((p) => presenceAt(p.key, f) >= 0.5 && charge(p.key) >= 0.5).length;
  const railFill = PAIRS5.reduce((s, p) => s + presenceAt(p.key, f) * clamp01(charge(p.key)), 0);
  const minutes = fedPairs * 10;

  const dim = dimAt(f);
  const ans = answerOpAt(f);
  const hull = hullAt(f);
  const hullPts = hullOf(P.slice(0, nodesDrawn), HULL_PAD);

  return (
    <div style={{ position: 'absolute', inset: 0, transform: `translateY(${driftAt(f)}px)` }}>
      <svg width={1080} height={1920} viewBox="0 0 1080 1920" style={{ position: 'absolute', left: 0, top: 0 }}>
        <g opacity={dim}>
          {/* everyone in the room at once — ONE shape, because inside it nobody is alone
              with anybody. It never touches an edge; an edge is one-on-one minutes. */}
          <Hull pts={hullPts} opacity={hull} label="MONDAY EVENING · 90 MIN TOGETHER" />

          {PAIRS5.map((p) => {
            const pres = presenceAt(p.key, f);
            if (pres <= 0.01) return null;
            const c = clamp01(charge(p.key));
            const flare = KEY4.has(p.key) ? flareAt(IDX4.get(p.key) ?? 0, f) : 0;
            const t = TURN_OF.get(p.key);
            return (
              <g key={p.key}>
                <EdgeLine
                  A={P[p.a]}
                  B={P[p.b]}
                  charge={Math.max(c, 0.34 * flare)}
                  opacity={pres}
                  ring={ringOf(p.key, f)}
                  label="10 MIN"
                  labelOpacity={t === TURNS[0] ? band(f, t.a + 6, t.a + 16, t.b + 30, t.b + 54) : 0}
                />
                {t ? (
                  <TurnDot
                    A={P[p.a]}
                    B={P[p.b]}
                    t={prog(f, t.a, t.b)}
                    opacity={band(f, t.a - 5, t.a + 4, t.b - 8, t.b)}
                  />
                ) : null}
              </g>
            );
          })}

          {HOUSE.map((person, i) => (
            <NodeDisc key={person.id} p={P[i]} person={person} r={NODE_R} opacity={i < N4 ? 1 : gran} />
          ))}
        </g>

        {/* ---- THE READOUTS. Six numbers, none of them a constant: the people drawn, the
             edges drawn, the pairs that have had their ten minutes, and n(n-1)/2 printed
             with the roster's own n. A mis-timed animation shows a WRONG number here
             instead of hiding behind a keyframed counter. --------------------------------- */}
        <FormulaChip n={nodesDrawn} cx={CX} y={CHIP_Y} opacity={chipOpAt(f)} />
        <g opacity={ans}>
          <Stat value={`${nodesDrawn}`} label="PEOPLE" x={230} y={STAT_Y} opacity={0.92} />
          <BigCount
            n={edgesDrawn}
            label="RELATIONSHIPS"
            x={CX}
            y={BIG_Y}
            color={NP.fed}
            pulse={Math.max(pop(f, COUNT_POP), pop(f, TEN_POP))}
          />
          <Stat
            value={`${minutes}`}
            label="MIN / WEEK"
            x={830}
            y={STAT_Y}
            color={minutes > 0 ? NP.fed : NP.text}
            opacity={0.92}
          />
          <g transform={`translate(${CX} ${RAIL_Y}) scale(${1 + 0.04 * Math.max(pop(f, ALONE_POP), pop(f, MIN_POP))}) translate(${-CX} ${-RAIL_Y})`}>
            <DayRail slots={edgesDrawn} filled={railFill} cx={CX} y={RAIL_Y} w={RAIL_W} />
          </g>
          <g opacity={pop(f, PEOPLE_POP) * 0.9}>
            <circle cx={230} cy={STAT_Y - 20} r={62} fill="none" stroke={NP.warn} strokeWidth={3} />
          </g>
        </g>
      </svg>
    </div>
  );
};

