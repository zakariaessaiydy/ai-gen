// The video's whole claim, asserted against the drawing rather than typed into it: the edges
// generated are the formula printed, and the rotation feeds every one of them exactly once —
// the four parent-child pairs, then the two nobody schedules.
if (PAIRS4.length !== nChoose2(N4) || PAIRS5.length !== nChoose2(N5)) {
  throw new Error('pairsOf disagrees with n(n-1)/2');
}
const ROTATION = [...K_ROTA, K_COUPLE, K_SIBS];
if (ROTATION.length !== PAIRS4.length || new Set(ROTATION).size !== PAIRS4.length || ROTATION.some((k) => !KEY4.has(k))) {
  throw new Error('the rotation does not cover the six relationships exactly once');
}
if (TURNS.length !== PAIRS4.length || TURNS.some((t, i) => t.key !== ROTATION[i])) {
  throw new Error('the turns on the timeline are not the rotation');
}
