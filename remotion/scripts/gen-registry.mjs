// Scans src/shots/**/*.tsx, extracts each file's compositionConfig, and writes:
//   src/registry.gen.tsx     — imports every shot for Root.tsx
//   src/shots.manifest.json  — metadata for the bulk renderer
// Run before `remotion studio` / render. VidTSX-skill files drop in and are picked up automatically.
// frames.mjs and render-all.mjs call generate() themselves, so a new shot is never "missing".
//
//   node scripts/gen-registry.mjs           regenerate (writes only files whose content changed)
//   node scripts/gen-registry.mjs --check   exit 1 if the committed registry is stale (CI / hooks)
import { existsSync, readdirSync, readFileSync, writeFileSync, statSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const shotsDir = path.join(root, 'src', 'shots');

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (name.endsWith('.tsx')) out.push(p);
  }
  return out;
}

function parseConfig(src) {
  const block = /export\s+const\s+compositionConfig\s*=\s*{([\s\S]*?)}\s*;/.exec(src);
  if (!block) return null;
  const body = block[1];
  const str = (k) => { const m = new RegExp('(?<![\\w$])' + k + "\\s*:\\s*['\"]([^'\"]+)['\"]").exec(body); return m ? m[1] : undefined; };
  const num = (k) => { const m = new RegExp('(?<![\\w$])' + k + "\\s*:\\s*([0-9.]+)").exec(body); return m ? Number(m[1]) : undefined; };
  const bool = (k) => new RegExp('(?<![\\w$])' + k + "\\s*:\\s*true").test(body);
  const id = str('id');
  if (!id) return null;
  return {
    id,
    durationInSeconds: num('durationInSeconds') ?? 5,
    fps: num('fps') ?? 30,
    width: num('width') ?? 1920,
    height: num('height') ?? 1080,
    transparent: bool('transparent'),
  };
}

// Only touch a file when its content actually changed: an unchanged mtime is what keeps the
// bundle cache (scripts/lib/bundle-cache.mjs) valid across a build that re-runs this.
function writeIfChanged(p, content) {
  if (existsSync(p) && readFileSync(p, 'utf8') === content) return false;
  writeFileSync(p, content);
  return true;
}

/**
 * Build the registry + manifest from src/shots. Returns { shots, changed } where `changed`
 * lists the files that differ from disk. write=false only compares (used by --check).
 * A missing/unreadable shots dir THROWS — an empty registry would silently drop every shot.
 */
export function generate({ write = true, quiet = false } = {}) {
  const files = walk(shotsDir);
  const shots = [];
  const seen = new Set();
  for (const file of files.sort()) {
    const cfg = parseConfig(readFileSync(file, 'utf8'));
    if (!cfg) { if (!quiet) console.warn('  skip (no compositionConfig):', path.relative(root, file)); continue; }
    if (seen.has(cfg.id)) { console.warn('  DUPLICATE id, skipping:', cfg.id, path.relative(root, file)); continue; }
    seen.add(cfg.id);
    const imp = './' + path.relative(path.join(root, 'src'), file).replace(/\\/g, '/').replace(/\.tsx$/, '');
    shots.push({ ...cfg, imp });
  }

  const header = '// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit.\n';
  let reg = header + "import type React from 'react';\n";
  shots.forEach((s, i) => { reg += `import Shot${i}, { compositionConfig as cfg${i} } from '${s.imp}';\n`; });
  reg += '\nexport const shots: { Comp: React.FC; config: any }[] = [\n';
  shots.forEach((s, i) => { reg += `  { Comp: Shot${i} as React.FC, config: cfg${i} },\n`; });
  reg += '];\n';

  const outputs = {
    [path.join(root, 'src', 'registry.gen.tsx')]: reg,
    [path.join(root, 'src', 'shots.manifest.json')]: JSON.stringify(shots.map(({ imp, ...m }) => m), null, 1),
  };
  const changed = [];
  for (const [p, content] of Object.entries(outputs)) {
    const same = existsSync(p) && readFileSync(p, 'utf8') === content;
    if (same) continue;
    changed.push(path.relative(root, p));
    if (write) writeIfChanged(p, content);
  }
  return { shots, changed };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  if (process.argv.includes('--check')) {
    const { shots, changed } = generate({ write: false, quiet: true });
    if (changed.length) {
      console.error(`gen-registry --check: stale ${changed.join(', ')} — run: cd remotion && npm run gen`);
      process.exit(1);
    }
    console.log(`gen-registry --check: up to date (${shots.length} shot(s))`);
  } else {
    const { shots, changed } = generate();
    console.log(`gen-registry: ${shots.length} shot(s) -> registry.gen.tsx${changed.length ? '' : ' (unchanged)'}`);
    shots.forEach((s) => console.log(`  - ${s.id}  ${s.width}x${s.height}@${s.fps} ${s.durationInSeconds}s${s.transparent ? ' [alpha]' : ''}`));
  }
}
