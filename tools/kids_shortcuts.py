#!/usr/bin/env python3
"""
kids_shortcuts.py — vertical YouTube Shorts (1080x1920) cut from the Tiny Sparks long (16:9) videos.

Reads kids-shorts/tiny-sparks/shortcuts.json — one entry per Short:
  {"day": 36, "comp": "KidsMorals036", "a": 25.6, "b": 67.6,  # the segment (s) of the long video
   "xc": 900, "w": 1080,                                       # the window: centre x + width in the 1920x1080
                                                               #   frame (1080 = square + sharp, 1440 = wider 4:3)
   "lines": ["MOMO'S HAND", "IS STUCK!"]}                      # the 2-line hook title (+ colors, scales, size)
For each Short: the window of the long video's render (remotion/out/<comp>.mp4, the sharp crf-18 master)
over a blurred, zoomed copy of itself, the KidsShortCards overlay on top (channel ribbon + title + window
edges), and the segment's audio from the PUBLISHED final (voice + SFX + music, short fades) →
<episode folder>/output/short-from-long.mp4 and a copy in kids-shorts/tiny-sparks/lab/shorts-out/.

  python tools/kids_shortcuts.py                # every entry
  python tools/kids_shortcuts.py --only 36,8    # some days (shorts.gen.ts always holds every entry)

Run from the repo root. Needs ffmpeg + node (the Remotion project). Keep a Short <= 60 s.
"""
import argparse
import glob
import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, "kids-shorts", "tiny-sparks", "shortcuts.json")
GEN_TS = os.path.join(ROOT, "remotion", "src", "shots", "kids-shortcuts", "shorts.gen.ts")
COLLECT = os.path.join(ROOT, "kids-shorts", "tiny-sparks", "lab", "shorts-out")
WIN_TOP = 400  # the square window spans y 400..1480; a wider window is centred on that band
KEYS = ("lines", "colors", "scales", "size")


def episode_dir(day):
    hits = [h for h in sorted(glob.glob(os.path.join(ROOT, "kids-shorts", "tiny-sparks", "*", f"day-{day:03d}-*"))) if os.path.isdir(h)]
    if not hits:
        sys.exit(f"day {day}: no kids-shorts/tiny-sparks/*/day-{day:03d}-* folder")
    return hits[0]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--only", help="comma list of days")
    ap.add_argument("--crf", type=int, default=21)
    args = ap.parse_args()
    spec = json.load(open(SPEC, encoding="utf-8"))
    only = {int(x) for x in args.only.split(",")} if args.only else None
    picked = [i for i, e in enumerate(spec) if not only or e["day"] in only]
    if not picked:
        sys.exit("nothing to do")

    data = [dict({"day": e["day"], "w": e.get("w", 1080)}, **{k: e[k] for k in KEYS if k in e}) for e in spec]
    with open(GEN_TS, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by tools/kids_shortcuts.py from kids-shorts/tiny-sparks/shortcuts.json — do not edit.\n")
        f.write(f"export const WIN_TOP = {WIN_TOP};\n")
        f.write("export type ShortCard = { day: number; w: number; lines: string[]; colors?: string[]; scales?: number[]; size?: number };\n")
        f.write("export const SHORTS: ShortCard[] = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")
    subprocess.run(["node", "scripts/frames.mjs", "KidsShortCards", ",".join(str(i) for i in picked), "--scale=1", "--no-sheet"],
                   cwd=os.path.join(ROOT, "remotion"), check=True)

    os.makedirs(COLLECT, exist_ok=True)
    for i in picked:
        e = spec[i]
        ep = episode_dir(e["day"])
        master = os.path.join(ROOT, "remotion", "out", f"{e['comp']}.mp4")
        finals = sorted(glob.glob(os.path.join(ep, "output", "*final*.mp4")))
        if not os.path.exists(master) or not finals:
            sys.exit(f"day {e['day']}: need remotion/out/{e['comp']}.mp4 and {ep}/output/*final*.mp4")
        a, b = float(e["a"]), float(e["b"])
        dur = b - a
        w = int(e.get("w", 1080))
        xc = float(e.get("xc", 960))
        x0 = int(round(min(1920 - w, max(0, xc - w / 2))))
        win_h = round(1080 * 1080 / w)
        top = WIN_TOP + (1080 - win_h) // 2
        bx = int(round(min(853 - 270, max(0, xc * 853 / 1920 - 135))))  # blurred backdrop: same spot, cover-cropped
        # masters can be 4K (render-all's default scale 2): crop in the master's own pixels (sharper)
        mw = int(subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width",
                                 "-of", "csv=p=0", master], capture_output=True, text=True).stdout.strip().rstrip(","))
        k = mw / 1920
        card = os.path.join(ROOT, "remotion", "out", "qa", f"KidsShortCards-f{i:04d}.png")
        out = os.path.join(ep, "output", "short-from-long.mp4")
        fc = (f"[0:v]split=2[s1][s2];"
              f"[s1]scale=-2:480,crop=270:480:{bx}:0,boxblur=10:2,scale=1080:1920,eq=brightness=-0.05:saturation=1.15[bg];"
              f"[s2]crop={round(w * k)}:{round(1080 * k)}:{round(x0 * k)}:0,scale=1080:{win_h}:flags=lanczos[fg];"
              f"[bg][fg]overlay=0:{top}[v1];[v1][2:v]overlay=0:0,format=yuv420p[v];"
              f"[1:a]afade=t=in:d=0.12,afade=t=out:st={max(0.0, dur - 0.7):.3f}:d=0.7[a]")
        subprocess.run(["ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
                        "-ss", f"{a:.3f}", "-t", f"{dur:.3f}", "-i", master,
                        "-ss", f"{a:.3f}", "-t", f"{dur:.3f}", "-i", finals[0],
                        "-i", card, "-filter_complex", fc, "-map", "[v]", "-map", "[a]",
                        "-c:v", "libx264", "-preset", "medium", "-crf", str(args.crf), "-r", "30",
                        "-c:a", "aac", "-b:a", "160k", "-movflags", "+faststart", "-t", f"{dur:.3f}", out], check=True)
        shutil.copyfile(out, os.path.join(COLLECT, f"day-{e['day']:03d}-short.mp4"))
        mb = os.path.getsize(out) / 1e6
        print(f"  day {e['day']:3d}  {dur:5.1f}s  {mb:5.1f} MB -> {os.path.relpath(out, ROOT)}")


if __name__ == "__main__":
    main()
