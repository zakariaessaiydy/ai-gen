#!/usr/bin/env python3
"""
kids_thumbs.py — YouTube thumbnails (1280x720 JPG) for the Tiny Sparks kids channel.

Reads kids-shorts/tiny-sparks/thumbs.json: one entry per video —
  {"day": 36, "comp": "KidsMorals036", "t": 48.5,          # the moment (s) to grab from the render
   "z": 1.8, "fx": 840, "fy": 600,                         # zoom + focus point in the 1920x1080 frame
   "lines": ["OH NO!", "STUCK!"], "at": "right",           # 2-4 big words: left | right | top | bottom
   "sticker": "EN\\n+FR", "stickerAt": "tr", "ribbon": "tl"} # optional; also colors, scales, size, rot,
                                                           # bubbles {items, x, y, r, perRow} (number/letter balls)
then:
  1. extracts each background frame from the episode's PUBLISHED render (remotion/out/<comp>.mp4, the
     crf-18 master; else the episode's output/*final*.mp4) into media/projects/kids-thumbs/frames/
     (gitignored — regenerable), so the thumbnail always matches the video;
  2. writes remotion/src/shots/kids-thumbs/thumbs.gen.ts and renders the KidsThumbs composition
     (one frame per thumbnail) with scripts/frames.mjs;
  3. saves <episode folder>/thumbnail.jpg (YouTube limit 2 MB) and prints the QA contact sheets.

  python tools/kids_thumbs.py               # every entry
  python tools/kids_thumbs.py --only 36,35  # some days (frames 0..n-1 = those entries)

Run from the repo root. Needs ffmpeg + node (the Remotion project).
"""
import argparse
import glob
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, "kids-shorts", "tiny-sparks", "thumbs.json")
FRAMES = os.path.join(ROOT, "media", "projects", "kids-thumbs", "frames")
GEN_TS = os.path.join(ROOT, "remotion", "src", "shots", "kids-thumbs", "thumbs.gen.ts")
KEYS = ("lines", "colors", "scales", "size", "at", "rot", "sticker", "stickerAt", "stickerColor", "ribbon", "bubbles")


def episode_dir(day):
    hits = sorted(glob.glob(os.path.join(ROOT, "kids-shorts", "tiny-sparks", "*", f"day-{day:03d}-*")))
    hits = [h for h in hits if os.path.isdir(h)]
    if not hits:
        sys.exit(f"day {day}: no kids-shorts/tiny-sparks/*/day-{day:03d}-* folder")
    return hits[0]


def source_video(e, ep):
    master = os.path.join(ROOT, "remotion", "out", f"{e['comp']}.mp4")
    if os.path.exists(master):
        return master
    finals = sorted(glob.glob(os.path.join(ep, "output", "*final*.mp4")))
    if finals:
        return finals[0]
    sys.exit(f"day {e['day']}: no render (remotion/out/{e['comp']}.mp4) and no output/*final*.mp4")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--only", help="comma list of days")
    args = ap.parse_args()
    spec = json.load(open(SPEC, encoding="utf-8"))
    only = {int(x) for x in args.only.split(",")} if args.only else None
    items = [e for e in spec if not only or e["day"] in only]
    if not items:
        sys.exit("nothing to do")
    os.makedirs(FRAMES, exist_ok=True)

    data = []
    for e in items:
        ep = episode_dir(e["day"])
        name = f"d{e['day']:03d}-{e['t']:.2f}.png"
        out = os.path.join(FRAMES, name)
        if not os.path.exists(out):
            subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-ss", f"{e['t']:.3f}", "-i", source_video(e, ep),
                            "-frames:v", "1", out], check=True)
        d = {"day": e["day"], "frame": name, "z": e.get("z", 1.0), "fx": e.get("fx", 960), "fy": e.get("fy", 540)}
        d.update({k: e[k] for k in KEYS if k in e})
        data.append((d, ep))

    with open(GEN_TS, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by tools/kids_thumbs.py from kids-shorts/tiny-sparks/thumbs.json — do not edit.\n")
        f.write("export type Thumb = { day: number; frame: string; z: number; fx: number; fy: number; lines: string[];\n"
                "  colors?: string[]; scales?: number[]; size?: number; at?: 'left' | 'right' | 'top' | 'bottom'; rot?: number;\n"
                "  sticker?: string; stickerAt?: string; stickerColor?: string; ribbon?: string;\n"
                "  bubbles?: { items: string[]; x: number; y: number; r?: number; perRow?: number } };\n")
        f.write("export const THUMBS: Thumb[] = " + json.dumps([d for d, _ in data], indent=1, ensure_ascii=False) + ";\n")

    frames = ",".join(str(i) for i in range(len(data)))
    subprocess.run(["node", "scripts/frames.mjs", "KidsThumbs", frames, "--scale=1"], cwd=os.path.join(ROOT, "remotion"), check=True)
    for i, (d, ep) in enumerate(data):
        png = os.path.join(ROOT, "remotion", "out", "qa", f"KidsThumbs-f{i:04d}.png")
        jpg = os.path.join(ep, "thumbnail.jpg")
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", png, "-q:v", "2", jpg], check=True)
        kb = os.path.getsize(jpg) // 1024
        print(f"  day {d['day']:3d} -> {os.path.relpath(jpg, ROOT)}  ({kb} KB)")
    print("QA sheets: remotion/out/qa/KidsThumbs-sheet*.png")


if __name__ == "__main__":
    main()
